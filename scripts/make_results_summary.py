"""Regenerate every headline number from the immutable raw rows in runs/.

Documentation discipline: the execution log is prose and can drift; `runs/*.json` cannot. Every
number quoted in a paper should be re-derived from a run record, never copied from a summary. This
script is that derivation, and its output is regenerated rather than edited.

Usage:  uv run python scripts/make_results_summary.py > docs/RESULTS.md
"""
import json
import pathlib

import numpy as np

RUNS = pathlib.Path("runs")


def _load(name):
    p = RUNS / name
    return json.loads(p.read_text()) if p.exists() else None


def _dsec(row, key):
    v = np.array(row["D_sec_per_traj"], float) if "D_sec_per_traj" in row else None
    return float(np.nanmedian(np.abs(v))) if v is not None else float("nan")


def _eff(d, lo="0.0", hi="0.02", field="by_eps"):
    """Percent change in median abs D_sec from `lo` to `hi`, plus the null counts."""
    rec = d["recovered"][0]
    b = _dsec(rec[field][lo], None); c = _dsec(rec[field][hi], None)
    rn = np.array([_dsec(x[field][hi], None) for x in d.get("random", [])])
    tn = np.array([_dsec(x[field][hi], None) for x in d.get("tangent", [])])
    return {"baseline": b, "effect_pct": 100 * (c - b) / b,
            "n_random": len(rn), "random_beats": int((rn < c).sum()),
            "random_pct": 100 * (np.median(rn) - b) / b if len(rn) else float("nan"),
            "n_tangent": len(tn), "tangent_beats": int((tn < c).sum()),
            "tangent_pct": 100 * (np.median(tn) - b) / b if len(tn) else float("nan")}


def section(t):
    print(f"\n## {t}\n")


def row(*c):
    print("| " + " | ".join(str(x) for x in c) + " |")


