section("E4: counterfactual dialing (transfer correlation)")
print("Source: `e4_s{3,4,5}.json`\n")
def _rank(x):
    x = np.asarray(x, float); o = np.argsort(x); r = np.empty(len(x)); r[o] = np.arange(len(x)); return r
def _sp(a, b):
    ra, rb = _rank(a) - _rank(a).mean(), _rank(b) - _rank(b).mean()
    return float((ra @ rb) / np.sqrt((ra @ ra) * (rb @ rb) + 1e-30))
row("seed", "Spearman(intended dC, realised dE)", "Spearman(realised dE, TRUE dE)", "controls beating")
row("---", "---", "---", "---")
for s in (3, 4, 5):
    d = _load(f"e4_s{s}.json")
    if not d: continue
    rec = d["recovered"][0]; k = np.array(rec["a_keep"], bool)
    dC = np.array(rec["a_intended_dC"])[k]; dE = np.array(rec["a_realised_dE"])[k]; dT = np.array(rec["a_true_dE"])[k]
    rho = _sp(dC, dE)
    ctl = []
    for arm in ("random", "tangent"):
        for r in d.get(arm, []):
            kk = np.array(r["a_keep"], bool)
            ctl.append(_sp(np.array(r["a_intended_dC"])[kk], np.array(r["a_realised_dE"])[kk]))
    ctl = np.array(ctl)
    row(s, f"{rho:+.3f}", f"{_sp(dE, dT):+.3f}", f"{int((ctl > rho).sum())}/{len(ctl)}")

